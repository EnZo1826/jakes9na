import { useEffect, useState } from 'react';
import { getProfile } from '../content/loader';
import SectionHeading from '../components/SectionHeading';
import Panel from '../components/Panel';
import { useScrollReveal } from '../hooks/useScrollReveal';

interface GithubRepo {
  name: string;
  description?: string;
  url: string;
  language?: string;
}

interface GithubActivityPayload {
  generated_at: string;
  stats?: Record<string, string | number>;
  repos?: GithubRepo[];
}

type FetchState =
  | { status: 'loading' }
  | { status: 'ready'; data: GithubActivityPayload }
  | { status: 'unavailable' };

function humanizeKey(key: string): string {
  return key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

/**
 * Reads public/data/github.json at RUNTIME (fetch, not bundled). That file
 * is generated by a separate CI job and is not present in this PR. When
 * absent or unreachable, this renders a static fallback panel sourced from
 * profile.json — never invented counts.
 */
export default function GithubActivity() {
  const profile = getProfile();
  const [state, setState] = useState<FetchState>({ status: 'loading' });
  const revealRef = useScrollReveal<HTMLDivElement>();

  useEffect(() => {
    let cancelled = false;

    fetch(`${import.meta.env.BASE_URL}data/github.json`)
      .then((response) => {
        if (!response.ok) throw new Error(`status ${response.status}`);
        return response.json() as Promise<GithubActivityPayload>;
      })
      .then((data) => {
        if (!cancelled) setState({ status: 'ready', data });
      })
      .catch(() => {
        if (!cancelled) setState({ status: 'unavailable' });
      });

    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <section id="github-activity" aria-labelledby="github-activity-heading" className="border-b border-line px-6 py-20">
      <div className="mx-auto max-w-5xl">
        <SectionHeading
          id="github-activity-heading"
          eyebrow="GitHub Activity"
          title="Live from GitHub"
          description="Refreshed by a scheduled job. If it hasn't run yet, or the fetch fails, a static panel is shown instead."
        />

        <div ref={revealRef}>
        {state.status === 'loading' ? (
          <Panel className="p-6">
            <p className="text-text" role="status">
              Checking for live GitHub data&hellip;
            </p>
          </Panel>
        ) : state.status === 'ready' ? (
          <div>
            <p className="font-mono text-xs uppercase tracking-wider text-teal">
              Last updated: {new Date(state.data.generated_at).toLocaleString('en-ZA', { timeZone: profile.timezone })}
            </p>

            {state.data.stats ? (
              <dl className="mt-4 grid grid-cols-2 gap-4 sm:grid-cols-4">
                {Object.entries(state.data.stats).map(([key, value]) => (
                  <Panel key={key} className="p-4">
                    <dt className="font-mono text-xs uppercase tracking-wider text-text">{humanizeKey(key)}</dt>
                    <dd className="mt-1 text-2xl font-semibold text-text-strong">{value}</dd>
                  </Panel>
                ))}
              </dl>
            ) : null}

            {state.data.repos && state.data.repos.length > 0 ? (
              <ul className="mt-6 grid gap-4 sm:grid-cols-2">
                {state.data.repos.map((repo) => (
                  <li key={repo.url}>
                    <Panel className="p-4">
                      <a href={repo.url} className="font-medium text-text-strong underline-offset-4 hover:underline">
                        {repo.name}
                      </a>
                      {repo.description ? <p className="mt-1 text-sm text-text">{repo.description}</p> : null}
                      {repo.language ? (
                        <p className="mt-2 font-mono text-[10px] uppercase tracking-wider text-teal">{repo.language}</p>
                      ) : null}
                    </Panel>
                  </li>
                ))}
              </ul>
            ) : null}
          </div>
        ) : (
          <Panel className="p-6">
            <p className="text-text">
              Live activity data is not available in this build. The GitHub profile below is sourced directly from
              this site&rsquo;s own content.
            </p>
            <a
              href={profile.github.url}
              className="mt-3 inline-block font-mono text-sm uppercase tracking-wider text-teal underline-offset-4 hover:underline"
            >
              {profile.github.url.replace('https://', '')}
            </a>
          </Panel>
        )}
        </div>
      </div>
    </section>
  );
}
