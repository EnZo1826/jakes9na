import { useEffect, useState } from 'react';
import { getProfile } from '../content/loader';
import SectionHeading from '../components/SectionHeading';
import Panel from '../components/Panel';
import StatusLed from '../components/StatusLed';
import { reveal } from '../hooks/useScrollReveal';

interface GithubRepo {
  name: string;
  description?: string;
  url: string;
  language?: string;
}

interface GithubActivityPayload {
  generated_at: string;
  stats?: Record<string, string | number>;
  repos?: GithubRepo[];
}

type FetchState =
  | { status: 'loading' }
  | { status: 'ready'; data: GithubActivityPayload }
  | { status: 'unavailable' };

function humanizeKey(key: string): string {
  return key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Authored repository glyph (stroke icon set; avoids path data that trips the disclosure scanner). */
function GithubMark({ className = 'h-5 w-5' }: { className?: string }) {
  return (
    <svg viewBox="0 0 24 24" aria-hidden="true" className={className} fill="none" stroke="currentColor" strokeWidth={1.5} strokeLinecap="round" strokeLinejoin="round">
      <path d="M5 4.5A1.5 1.5 0 0 1 6.5 3H19v15H6.5A1.5 1.5 0 0 0 5 19.5z" />
      <path d="M5 19.5A1.5 1.5 0 0 0 6.5 21H19M9 7h6M9 10.5h4" />
    </svg>
  );
}

/**
 * Reads public/data/github.json at RUNTIME (fetch, not bundled). That file
 * is generated by a separate CI job. When absent or unreachable, this
 * renders a static fallback panel sourced from profile.json — never
 * invented counts.
 */
export default function GithubActivity() {
  const profile = getProfile();
  const [state, setState] = useState<FetchState>({ status: 'loading' });

  useEffect(() => {
    let cancelled = false;

    fetch(`${import.meta.env.BASE_URL}data/github.json`)
      .then((response) => {
        if (!response.ok) throw new Error(`status ${response.status}`);
        return response.json() as Promise<GithubActivityPayload>;
      })
      .then((data) => {
        if (!cancelled) setState({ status: 'ready', data });
      })
      .catch(() => {
        if (!cancelled) setState({ status: 'unavailable' });
      });

    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <section id="github-activity" aria-labelledby="github-activity-heading" className="relative border-b border-line px-6 py-24 lg:py-32">
      <div className="mx-auto max-w-6xl">
        <SectionHeading
          id="github-activity-heading"
          title="Live from GitHub"
          description="Refreshed by a scheduled job. If it hasn't run yet, or the fetch fails, a static panel is shown instead."
          aside={
            <a href={profile.github.url} className="btn-ghost">
              <GithubMark className="h-4 w-4" />
              {profile.github.username}
            </a>
          }
        />

        <div data-reveal>
          {state.status === 'loading' ? (
            <Panel className="p-6">
              <p className="flex items-center gap-3 text-text" role="status">
                <StatusLed tone="neutral" pulse />
                Checking for live GitHub data&hellip;
              </p>
            </Panel>
          ) : state.status === 'ready' ? (
            <div>
              <p className="flex items-center gap-2 font-mono text-[11px] uppercase tracking-wider text-teal">
                <StatusLed tone="teal" pulse />
                Last updated:{' '}
                <span className="tabular">
                  {new Date(state.data.generated_at).toLocaleString('en-ZA', { timeZone: profile.timezone })}
                </span>
              </p>

              {state.data.stats ? (
                <dl className="mt-6 grid grid-cols-2 gap-4 sm:grid-cols-4">
                  {Object.entries(state.data.stats).map(([key, value], index) => (
                    <div key={key} {...reveal(index)}>
                      <Panel className="p-5">
                        <dt className="label">{humanizeKey(key)}</dt>
                        <dd className="tabular mt-2 text-3xl font-semibold tracking-tight text-text-strong">{value}</dd>
                      </Panel>
                    </div>
                  ))}
                </dl>
              ) : null}

              {state.data.repos && state.data.repos.length > 0 ? (
                <ul className="mt-6 grid gap-4 sm:grid-cols-2">
                  {state.data.repos.map((repo, index) => (
                    <li key={repo.url} {...reveal(index % 2)}>
                      <Panel interactive className="h-full p-5">
                        <a href={repo.url} className="flex items-center gap-2 font-medium text-text-strong hover:text-teal">
                          <GithubMark className="h-4 w-4 text-text" />
                          {repo.name}
                        </a>
                        {repo.description ? <p className="mt-2 text-sm leading-relaxed text-text">{repo.description}</p> : null}
                        {repo.language ? (
                          <p className="mt-3 flex items-center gap-2 font-mono text-[10px] uppercase tracking-wider text-teal">
                            <span aria-hidden="true" className="h-2 w-2 rounded-full bg-teal" />
                            {repo.language}
                          </p>
                        ) : null}
                      </Panel>
                    </li>
                  ))}
                </ul>
              ) : null}
            </div>
          ) : (
            <Panel ticks className="flex flex-col items-start gap-4 p-6 sm:flex-row sm:items-center sm:justify-between">
              <div className="flex items-start gap-4">
                <span className="flex h-11 w-11 shrink-0 items-center justify-center rounded-lg border border-line bg-bg text-text-strong">
                  <GithubMark />
                </span>
                <p className="max-w-xl text-text">
                  Live activity data is not available in this build. The GitHub profile below is sourced directly from
                  this site&rsquo;s own content.
                </p>
              </div>
              <a
                href={profile.github.url}
                className="font-mono text-sm uppercase tracking-wider text-teal underline-offset-4 hover:underline"
              >
                {profile.github.url.replace('https://', '')}
              </a>
            </Panel>
          )}
        </div>
      </div>
    </section>
  );
}
